class I18nManager:
    """Manages internationalization and localized text strings."""

    def __init__(self, current_lang: str = "en"):
        self.current_lang = current_lang if current_lang in LANGUAGES else "en"

    def set_language(self, lang_code: str) -> None:
        if lang_code in LANGUAGES:
            self.current_lang = lang_code

    def get(self, key: str, *args, **kwargs) -> str:
        """
        Get localized text for key.
        Falls back to English if missing in current language,
        or returns key name if missing completely.
        """
        lang_dict = LANGUAGES.get(self.current_lang, LANGUAGES["en"])
        text = lang_dict.get(key)
        
        if text is None:
            text = LANGUAGES["en"].get(key, key)

        if args or kwargs:
            try:
                return text.format(*args, **kwargs)
            except Exception:
                return text
        return text
